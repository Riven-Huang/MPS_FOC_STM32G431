% Plot measured ripple for inverting (negative) and rectifying (positive) power.
clc;
clearvars;
close all;

frontpt = 10;
scriptFolder = fileparts(mfilename("fullpath"));
pngOutputPath = fullfile(scriptFolder, "bidirectional_operating_point_sweep.png");
pdfOutputPath = fullfile(scriptFolder, "bidirectional_operating_point_sweep.pdf");

%% Experimental operating points
powerMagnitudeW = [250, 500, 1000, 1500];
methodNames = ["PI", "PIR", "ZPIR", "VOPIR"];
% Rows: PI, PIR, ZPIR, VOPIR. Columns follow powerMagnitudeW.
rectifyingRippleV = [ ...
    2.88, 3.30, 3.67, 4.30; ...
    1.88, 2.10, 2.60, 3.67; ...
    1.78, 1.99, 2.53, 3.49; ...
    0.82, 1.25, 1.88, 3.20];
invertingRippleV = [ ...
    2.78, 3.14, 3.46, 4.14; ...
    1.47, 1.63, 1.92, 2.56; ...
    1.41, 1.52, 1.83, 2.40; ...
    0.83, 1.36, 1.62, 2.14];

% Reverse both power and data so the negative branch runs from -1500 to -250 W.
% NaN separates the branches because no zero-power measurement is available.
powerW = [-fliplr(powerMagnitudeW), NaN, powerMagnitudeW];
ripplePeakToPeakV = [fliplr(invertingRippleV), ...
    nan(numel(methodNames), 1), rectifyingRippleV];
assert(size(ripplePeakToPeakV, 1) == numel(methodNames));
assert(size(ripplePeakToPeakV, 2) == numel(powerW));

%% TTE-compatible single-column figure
figureWidthCm = 8.89;
figureHeightCm = 6.15;
lineColors = [ ...
    0.20, 0.20, 0.20; ...
    0.00, 0.45, 0.74; ...
    0.49, 0.18, 0.56; ...
    0.00, 0.55, 0.35];
lineStyles = ["-.", "--", "-", ":"];
lineWidths = [1.2, 1.3, 1.4, 1.5];
markers = ["s", "^", "d", "o"];

fig = figure(Color="w", Units="centimeters", ...
    Position=[3, 3, figureWidthCm, figureHeightCm]);
ax = axes(fig);
hold(ax, "on");
plotHandles = gobjects(1, numel(methodNames));
for methodIndex = 1:numel(methodNames)
    plotHandles(methodIndex) = plot(ax, powerW, ...
        ripplePeakToPeakV(methodIndex, :), ...
        Color=lineColors(methodIndex, :), ...
        LineStyle=lineStyles(methodIndex), ...
        LineWidth=lineWidths(methodIndex), ...
        Marker=markers(methodIndex), MarkerSize=5, ...
        MarkerFaceColor="w", DisplayName=methodNames(methodIndex));
end
xline(ax, 0, "-", Color=[0.5, 0.5, 0.5], LineWidth=0.75, ...
    HandleVisibility="off");
xlabel(ax, "PCC Power (W)", FontName="Arial", FontSize=frontpt);
ylabel(ax, "DC-Link Voltage Ripple (V)", FontName="Arial", FontSize=frontpt);
xticks(ax, -1500:500:1500);
xlim(ax, [-1600, 1600]);
maximumRippleV = max(ripplePeakToPeakV, [], "all", "omitnan");
ylim(ax, [0, ceil(maximumRippleV + 1.5)]);
text(ax, -650, 4.05, "Inverting Mode", HorizontalAlignment="center", ...
    FontName="Arial", FontSize=frontpt);
text(ax, 650, 4.05, "Rectifying Mode", HorizontalAlignment="center", ...
    FontName="Arial", FontSize=frontpt);
grid(ax, "on");
box(ax, "on");
legend(ax, plotHandles([1, 3, 2, 4]), Location="north", NumColumns=2, ...
    FontName="Arial", FontSize=frontpt, Box="on", Color="w", EdgeColor="k");
set(ax, FontName="Arial", FontSize=frontpt, LineWidth=0.75, ...
    TickDir="in", Layer="top", GridAlpha=0.25, MinorGridAlpha=0.12);
set(fig, PaperUnits="centimeters", ...
    PaperPosition=[0, 0, figureWidthCm, figureHeightCm], ...
    PaperSize=[figureWidthCm, figureHeightCm]);
exportgraphics(fig, pngOutputPath, Resolution=600, BackgroundColor="white");
print(fig, pdfOutputPath, "-dpdf", "-vector");

%% Numerical summary with signed power
measuredColumns = isfinite(powerW);
resultTable = array2table([powerW(measuredColumns).', ...
    ripplePeakToPeakV(:, measuredColumns).'], ...
    VariableNames=["PowerW", methodNames]);
disp(resultTable);
